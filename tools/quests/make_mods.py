#!/usr/bin/env python3
"""Build tools/quests/mods.json: every mod in the pack, its mod ids, and what it adds.

    python tools/quests/make_mods.py <folder of the pack's mod jars> [pack dir]

Reads mods/*.pw.toml for names and sides, each jar's META-INF/mods.toml for its mod ids, and registry.json for
what each mod id adds (items, mobs, biomes, structures). Content that a mod adds under another namespace (a
datapack-style mod like Dungeons and Taverns) is attached through EXTRA_NAMESPACES. Each mod's role (whether it
should appear in quests) comes from tools/quests/src/mod_roles.json; coverage.py uses it.
"""
import json
import os
import sys
import tomllib
import zipfile
from collections import Counter, defaultdict

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
# mods whose content lives under a namespace other than their mod id
EXTRA_NAMESPACES = {'mr_dungeons_andtaverns': ['nova_structures'], 't_and_t': ['towns_and_towers'],
                    'moremobvariants': ['variants']}


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    jars, pack = sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else ROOT
    reg = json.load(open(os.path.join(pack, 'tools', 'quests', 'registry.json')))
    by_ns = defaultdict(lambda: defaultdict(list))
    for kind in ('items', 'entities', 'biomes', 'structures'):
        for ident in reg.get(kind, []):
            by_ns[ident.split(':', 1)[0]][kind].append(ident)
    out = {}
    for f in sorted(os.listdir(os.path.join(pack, 'mods'))):
        if not f.endswith('.pw.toml'):
            continue
        meta = tomllib.load(open(os.path.join(pack, 'mods', f), 'rb'))
        ids = []
        jar = os.path.join(jars, meta['filename'])
        if os.path.exists(jar):
            with zipfile.ZipFile(jar) as z:
                if 'META-INF/mods.toml' in z.namelist():
                    toml = tomllib.loads(z.read('META-INF/mods.toml').decode('utf-8', 'replace'))
                    ids = [m['modId'] for m in toml.get('mods', [])]
        slug = f[:-len('.pw.toml')]
        namespaces = ids + [n for i in ids for n in EXTRA_NAMESPACES.get(i, [])]
        content = {k: sorted(v for ns in namespaces for v in by_ns.get(ns, {}).get(k, []))
                   for k in ('items', 'entities', 'biomes', 'structures')}
        out[ids[0] if ids else slug] = {
            'name': meta['name'], 'slug': slug, 'side': meta.get('side', 'both'), 'mod_ids': ids,
            'counts': {k: len(v) for k, v in content.items() if v},
            'entities': content['entities'], 'structures': content['structures'],
        }
    path = os.path.join(pack, 'tools', 'quests', 'mods.json')
    with open(path, 'w', encoding='utf-8', newline='\n') as fh:
        json.dump({'_about': 'Generated by make_mods.py: every mod, its ids and what it adds. Keyed by main mod id.',
                   **out}, fh, indent=1)
        fh.write('\n')
    print(f'{len(out)} mods, {sum(1 for m in out.values() if m["counts"])} add items, mobs, biomes or structures')


if __name__ == '__main__':
    main()
