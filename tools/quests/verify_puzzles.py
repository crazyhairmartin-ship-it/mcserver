"""Check every quest puzzle against real generated structures on the test server.

    python tools/quests/verify_puzzles.py [copies] [container]

Reads the generated quest data (kubejs/server_scripts/quest_givers.generated.js). For each "use" step at a structure
(right-click N of a block) and each "search" step (N containers), runs /fotfverify on the test server (docker
container "fotf-test", default) to generate that many copies of the structure (default 3) and count the blocks inside
them. Writes tools/quests/src/plans/puzzle_check.md (spoilers): every step, the fewest any copy had, and OK or SHORT.
A SHORT step needs fixing: lower its count to what every copy has, switch it to "search", or have the player bring
the block ("build").

Needs the test server running a pack with the fotfskills /fotfverify command. Structures in a #group are checked
through their first three members.
"""
import json
import os
import re
import subprocess
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
GIVERS = os.path.join(ROOT, 'kubejs', 'server_scripts', 'quest_givers.generated.js')
OUT = os.path.join(ROOT, 'tools', 'quests', 'src', 'plans', 'puzzle_check.md')


def givers():
    text = open(GIVERS, encoding='utf-8').read()
    m = re.search(r'global\.QUEST_GIVERS = (\[.*?\n\])\n', text, re.S)
    return json.loads(m.group(1))


def rcon(container, cmd):
    out = subprocess.run(['docker', 'exec', container, 'rcon-cli', '--', cmd], capture_output=True, text=True,
                         timeout=900).stdout
    return re.sub(r'\x1b\[[0-9;]*m', '', out)


def main():
    copies = int(sys.argv[1]) if len(sys.argv) > 1 else 3
    container = sys.argv[2] if len(sys.argv) > 2 else 'fotf-test'
    checks = []   # (quest, step kind, structure ids, key, needed)
    for g in givers():
        at = g.get('at') or {}
        if at.get('kind') != 'structure':
            continue
        sids = [s for s in at['structures'] if not s.startswith('#')][:3]
        if g['type'] == 'use':
            checks.append((g['quest'], 'use', sids, ','.join(g['keys']), g['count']))
        elif g['type'] == 'search':
            checks.append((g['quest'], 'search', sids, 'containers', g['count']))
    results = {}
    for sid in sorted({s for c in checks for s in c[2]}):
        keys = sorted({c[3] for c in checks if sid in c[2]})
        flat = sorted({k for ks in keys for k in ks.split(',')})
        print(f'checking {sid} ({", ".join(flat)})...', flush=True)
        out = rcon(container, f'fotfverify {sid} {copies} {",".join(flat)}')
        lines = [l for l in out.splitlines() if l.startswith('fotfverify')]
        summary = next((l for l in lines if ' summary ' in l), '')
        found = int(re.search(r'copies=(\d+)', summary).group(1)) if summary else 0
        mins = dict(re.findall(r'(\S+)_min=(\d+)', summary))
        results[sid] = (found, {k: int(v) for k, v in mins.items()}, [l for l in lines if ' copy ' in l])
    rows, short = [], 0
    for quest, kind, sids, key, need in checks:
        for sid in sids:
            found, mins, _ = results.get(sid, (0, {}, []))
            have = min((mins.get(k, 0) for k in key.split(',')), default=0) if ',' not in key else \
                sum(mins.get(k, 0) for k in key.split(','))
            status = 'NOT FOUND' if not found else ('OK' if have >= need else 'SHORT')
            short += status != 'OK'
            rows.append(f'| {quest} | {kind} | {sid} | {key} | {need} | {have} (of {found} copies) | {status} |')
    with open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('# Puzzle check (SPOILERS)\n\nGenerated by tools/quests/verify_puzzles.py on the test server: each '
                 'puzzle step against the fewest blocks any generated copy of its structure had.\n\n'
                 '| quest | step | structure | blocks | needs | fewest found | |\n|---|---|---|---|---|---|---|\n')
        fh.write('\n'.join(rows) + '\n\n## Copies\n\n')
        for sid, (found, mins, lines) in sorted(results.items()):
            fh.write(f'- **{sid}**: {found} copies\n' + ''.join(f'  - `{l}`\n' for l in lines))
    print(f'{len(rows)} checks, {short} need attention: {os.path.relpath(OUT, ROOT)}')


if __name__ == '__main__':
    main()
